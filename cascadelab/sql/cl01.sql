-- CL01: ON DELETE CASCADE 4단 (A -> B -> C -> D). 트리거 없음.
USE CascadeLab;
GO
CREATE SCHEMA cl01;
GO
CREATE TABLE cl01.A (
    id   int         NOT NULL CONSTRAINT PK_cl01_A PRIMARY KEY,
    name varchar(20) NOT NULL
);
CREATE TABLE cl01.B (
    id   int NOT NULL CONSTRAINT PK_cl01_B PRIMARY KEY,
    a_id int NOT NULL CONSTRAINT FK_cl01_B_A REFERENCES cl01.A (id) ON DELETE CASCADE
);
CREATE TABLE cl01.C (
    id   int NOT NULL CONSTRAINT PK_cl01_C PRIMARY KEY,
    b_id int NOT NULL CONSTRAINT FK_cl01_C_B REFERENCES cl01.B (id) ON DELETE CASCADE
);
CREATE TABLE cl01.D (
    id   int NOT NULL CONSTRAINT PK_cl01_D PRIMARY KEY,
    c_id int NOT NULL CONSTRAINT FK_cl01_D_C REFERENCES cl01.C (id) ON DELETE CASCADE
);
GO
