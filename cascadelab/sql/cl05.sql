-- CL05: 한 부모에서 갈라지는 CASCADE 체인 2개 (P -> X -> X2, P -> Y -> Y2). 트리거 없음.
USE CascadeLab;
GO
CREATE SCHEMA cl05;
GO
CREATE TABLE cl05.P (
    id int NOT NULL CONSTRAINT PK_cl05_P PRIMARY KEY
);
CREATE TABLE cl05.X (
    id   int NOT NULL CONSTRAINT PK_cl05_X PRIMARY KEY,
    p_id int NOT NULL CONSTRAINT FK_cl05_X_P REFERENCES cl05.P (id) ON DELETE CASCADE
);
CREATE TABLE cl05.X2 (
    id   int NOT NULL CONSTRAINT PK_cl05_X2 PRIMARY KEY,
    x_id int NOT NULL CONSTRAINT FK_cl05_X2_X REFERENCES cl05.X (id) ON DELETE CASCADE
);
CREATE TABLE cl05.Y (
    id   int NOT NULL CONSTRAINT PK_cl05_Y PRIMARY KEY,
    p_id int NOT NULL CONSTRAINT FK_cl05_Y_P REFERENCES cl05.P (id) ON DELETE CASCADE
);
CREATE TABLE cl05.Y2 (
    id   int NOT NULL CONSTRAINT PK_cl05_Y2 PRIMARY KEY,
    y_id int NOT NULL CONSTRAINT FK_cl05_Y2_Y REFERENCES cl05.Y (id) ON DELETE CASCADE
);
GO
